const COLOR_MEANING: Record<string, string> = {
  '#3B82F6': 'blue, which the contract maps to clean, soot-free diffusion combustion',
  '#F97316': 'orange, which the contract maps to radiative, soot-heavy combustion',
}

export function isBurning(sim: Simulation3D): boolean {
  return sim.burn_rate_mm_s > 0 && sim.oxygen_factor > 0
}

function flameText(sim: Simulation3D): string {
  if (!isBurning(sim)) {
    return `No sustained flame. The simulation reports a burn rate of ${fmt(sim.burn_rate_mm_s, 2)} mm/s and an oxygen factor of ${fmt(sim.oxygen_factor, 2)}, so the 3D chamber fades the flame out and leaves only dissipating smoke.`
  }
  const shape =
    sim.flame_geometry === 'spherical'
      ? 'The flame is spherical: a quiescent diffusion flame ball, the shape expected in microgravity with airflow below 1 cm/s.'
      : 'The flame is elongated: the plume is stretched by forced ventilation or partial gravity.'
  const meaning = COLOR_MEANING[sim.flame_color_hex.toUpperCase()]
  const color = meaning
    ? `Its color (${sim.flame_color_hex}) is ${meaning}.`
    : `Its color is ${sim.flame_color_hex}; the contract defines no soot interpretation for this color.`
  return `${shape} ${color} The burn rate of ${fmt(sim.burn_rate_mm_s, 2)} mm/s drives the flame's emission speed and size, and the oxygen factor of ${fmt(sim.oxygen_factor, 2)} (0 to 1) scales its opacity and volume.`
}

/** Local calendar date as YYYY-MM-DD. */
export function isoDate(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
}

export function formatDateTime(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${isoDate(d)} ${pad(d.getHours())}:${pad(d.getMinutes())}`
}

export function reportFileName(scenarioId: string, d: Date): string {
  return `astrofire-analysis-${scenarioId}-${isoDate(d)}.pdf`
}

export function buildReport(result: SimulationResponse, options: { mock: boolean; generatedAt: Date }): ReportModel {
  const { inputs, telemetry: t, simulation_3d: sim, safety_copilot: copilot } = result
  const references: ReportReference[] = result.nasa_citations.filter(isCitationShown).map((c, i) => ({
    n: i + 1,
    id: c.id,
    title: c.title,
    url: c.url,
    finding: c.finding,
  }))
  const cite = references.length > 0 ? `[${references.map((r) => r.n).join(', ')}]` : ''
  const g = GROUNDING[result.grounding_status]
  const estimate = result.suppression_estimate

  const abstract =
    `This report analyzes ${inputs.material_name} (${fmt(inputs.thickness_mm, 2)} mm) in ${inputs.environment_label}, ` +
    `at ${fmt(inputs.o2_pct, 1)}% O2 and ${fmt(inputs.airflow_cm_s, 1)} cm/s airflow. ` +
    `The scenario has a flammability score of ${t.flammability_score}/100, rated "${t.risk_label}", ` +
    `a burn rate of ${fmt(sim.burn_rate_mm_s, 2)} mm/s and a minimum oxygen limit of ${fmt(t.oxygen_limit_pct, 1)}% O2. ` +
    `${copilot.diagnosis}${cite ? ` ${cite}` : ''}`

  return {
    scenarioId: result.scenario_id,
    generatedAt: options.generatedAt,
    mode: options.mock ? 'Mock' : 'Live',
    mock: options.mock,
    title: REPORT_TITLE,
    subtitle: `${inputs.environment_label} · ${inputs.material_name}`,
    grounding: { status: result.grounding_status, label: g.label, badge: g.badge, summary: g.summary },
    dataSources: references.length > 0 ? references.map((r) => shortCitationId(r.id)).join(', ') : NOT_AVAILABLE,
    abstract,
    parameters: [
      { label: 'Material', value: inputs.material_name, unit: '' },
      { label: 'Material ID', value: inputs.material_id, unit: '' },
      { label: 'Thickness', value: fmt(inputs.thickness_mm, 2), unit: 'mm' },
      { label: 'Gravity', value: fmt(inputs.gravity_g, 2), unit: 'g' },
      { label: 'Environment', value: inputs.environment_label, unit: '' },
      { label: 'Oxygen', value: fmt(inputs.o2_pct, 1), unit: '% O2' },
      { label: 'Airflow', value: fmt(inputs.airflow_cm_s, 1), unit: 'cm/s' },
    ],
    telemetry: [
      {
        label: 'Flammability score',
        value: String(t.flammability_score),
        unit: '/100',
        meaning: 'Composite risk index: 0–35 nominal, 36–70 moderate, 71–100 critical',
      },
      { label: 'Risk label', value: t.risk_label, unit: '', meaning: 'Severity category matching the score' },
      { label: 'Burn rate', value: fmt(sim.burn_rate_mm_s, 2), unit: 'mm/s', meaning: 'Flame spread rate over the material' },
      { label: 'Oxygen limit', value: fmt(t.oxygen_limit_pct, 1), unit: '% O2', meaning: 'Minimum oxygen needed to sustain the flame' },
      { label: 'CO', value: fmt(t.co_ppm, 0), unit: 'ppm', meaning: 'Estimated carbon monoxide byproduct' },
      { label: 'CO2', value: fmt(t.co2_pct, 1), unit: '%', meaning: 'Estimated carbon dioxide byproduct' },
    ],
    flame: { simulation: sim, burning: isBurning(sim), text: flameText(sim) },
    interpretation: copilot.diagnosis,
    suppression: {
      action: copilot.suppression_action,
      sizing: estimate
        ? [
            { label: 'Mist volume', value: fmt(estimate.estimated_mist_volume_ml, 0), unit: 'mL', meaning: 'Estimated fine water mist needed' },
            { label: 'Discharge time', value: fmt(estimate.estimated_discharge_seconds, 1), unit: 's', meaning: 'Estimated open-cabin discharge duration' },
            { label: 'Tank used', value: fmt(estimate.tank_capacity_used_pct, 1), unit: '%', meaning: 'Share of the ISS FWM PFE tank capacity' },
            { label: 'Cooling efficiency', value: fmt(estimate.cooling_efficiency_pct, 0), unit: '%', meaning: 'Gravity-bounded thermal cooling efficiency' },
            { label: 'Flame power', value: fmt(estimate.estimated_flame_power_kw, 2), unit: 'kW', meaning: 'Estimated heat release rate' },
          ]
        : null,
      note: estimate ? estimate.confined_rack_note : null,
    },
    terrestrial: copilot.terrestrial_spinoff,
    limitations: copilot.scientific_limitations,
    references,
    cite,
  }
}
